#ifndef SELECTION_H
#define SELECTION_H

/*
 * 开局角色选择向导：
 *   1. 输入玩家人数（仅允许 2~4，非法输入说明原因并要求重新输入）
 *   2. 按 玩家1 ~ 玩家N 的顺序依次引导选择互不重复的角色
 *      （非法字符 / 不存在的编号 / 重复角色均说明原因并允许重选）
 *   3. 展示选择结果并等待确认
 *
 * 返回值：
 *   1 = 玩家已确认选择，可以创建游戏；
 *   0 = 输入结束（EOF），未完成选择。
 *
 * 重要约束：本模块只收集“选择意向”（玩家人数 + 每人所选角色编号），
 * 不创建任何玩家 / 游戏数据。只有返回 1 之后调用方才允许创建游戏，
 * 因此选择失败或尚未确认时不存在半初始化的玩家数据。
 */
int selection_wizard(int *out_count, int out_chosen[]);

#endif /* SELECTION_H */
