#ifndef HELP_H
#define HELP_H

/*
 * 帮助模块（功能点 A6）：随时打开帮助界面查看完整指令集。
 *
 * 指令集（本版本列出全部 9 条命令的用途、参数与简短示例）：
 *   HELP    —— 查看命令帮助（打开本帮助界面，忽略大小写）
 *   ROLL    —— 掷骰子命令，行走 1~6 步，步数由随机算法产生
 *   STEP n  —— 遥控骰子，n 为指定的步数
 *   SELL n  —— 出售自己的房产，售价为投资总成本的 2 倍；n 为地图绝对位置
 *   BLOCK n —— 在前后 10 步内放置路障拦截经过的玩家；n 为相对距离，负数为后方
 *   BOMB n  —— 在前后 10 步内放置炸弹，经过者炸伤住院三天；n 为相对距离，负数为后方
 *   ROBOT   —— 清扫前方路面 10 步内的任何其他道具（炸弹、路障）
 *   QUERY   —— 显示自家资产
 *   QUIT    —— 强制退出，整局游戏结束
 *
 * 注意：本模块只实现“查看指令”功能；其余命令的功能由各自模块实现。
 */

/* 打印帮助界面：完整指令集（命令、用途、参数、简短示例）。随时可调用。 */
void help_print(void);

/*
 * 判断输入行（需已去掉首尾空格）是否为 HELP 命令。
 * HELP 命令忽略大小写：help / HELP / Help / hElP 等均返回 1；
 * 必须是整词（“helpme”“hel”等返回 0）。
 */
int help_is_help_command(const char *line);

#endif /* HELP_H */
